def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true",
                    help="실데이터가 있어도 더미를 섞어 넣는다 (권장하지 않음)")
    args = ap.parse_args()

    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    added = 0
    try:
        # 실데이터(source_key가 있는 행)가 이미 있으면 막는다.
        # 발표 직전에 실수로 이걸 돌려서 가짜 카페가 지도에 섞이는 사고를 방지한다.
        real = db.query(Cafe).filter(Cafe.source_key.is_not(None)).count()
        if real and not args.force:
            print(f"  [중단] 실데이터 {real}건이 이미 있습니다. 더미를 섞지 않습니다.")
            print("         실데이터 재적재:  python -m scripts.ingest_iddy --purge")
            print("         그래도 넣으려면:  python -m scripts.seed --force")
            return

        for r in ROWS:
            (name, region, district, lat, lng, o, c, closed,
             laptop, power, wifi, quiet, seats, reviews, rating) = r
            if db.query(Cafe).filter(Cafe.name == name).first():
                continue
            dist, remote = classify_remote(lat, lng)
            db.add(Cafe(
                name=name, category="음식점 > 카페", region=region, district=district,
                address=f"제주특별자치도 {region} {district}",
                road_address=f"제주특별자치도 {region} {district}",
                lat=lat, lng=lng,
                open_time=o, close_time=c, closed_days=closed,
                last_order_min=30, hours_source="manual",
                laptop_ok=bool(laptop), has_power=bool(power), has_wifi=bool(wifi),
                quiet=bool(quiet), seat_count=seats,
                # 리뷰가 아직 없는 매장 = 아무도 안 가봤으니 카공 정보도 추정치 상태.
                # /api/reports/wanted 가 이런 매장을 제보 미션으로 노출한다.
                cagong_source="estimated" if reviews < 3 else "owner",
                review_count=reviews, rating_avg=rating,
                dist_to_hotspot_km=dist, is_remote=remote,
            ))
            added += 1

        if not db.query(User).first():
            db.add(User(nickname="런케이션_데모", email="demo@jeju.dev", is_workationer=True))
            db.add(User(nickname="워케이셔너A", email="a@jeju.dev", is_workationer=True))

        db.commit()
        total = db.query(Cafe).count()
        remote_cnt = db.query(Cafe).filter(Cafe.is_remote.is_(True)).count()
        print(f"시드 완료: 신규 {added}건 / 전체 {total}건 (외곽 {remote_cnt}건)")
    finally:
        db.close()


if __name__ == "__main__":
    main()
